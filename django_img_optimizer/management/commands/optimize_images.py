# https://docs.djangoproject.com/en/5.0/howto/custom-management-commands/

from django.core.exceptions import ImproperlyConfigured
from django.core.management.base import BaseCommand, CommandError

from django_img_optimizer.utils import (
    ImageOptimizationError,
    delete_optimized_images,
    optimize_images,
)


class Command(BaseCommand):
    help = 'Generates AVIF and WebP alternatives for configured images.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--delete',
            action='store_true',
            help='Delete only AVIF and WebP files previously generated by django-img-optimizer.',
        )

    def handle(self, *args, **options):
        try:
            if options['delete']:
                deleted_count = delete_optimized_images()
                self.stdout.write(
                    self.style.SUCCESS(f'Deleted {deleted_count} optimized image(s).')
                )
                return

            summary = optimize_images()
        except (ImproperlyConfigured, ImageOptimizationError) as error:
            raise CommandError(str(error)) from error

        self.stdout.write(
            self.style.SUCCESS(
                'Image optimization complete. '
                f"Generated: {summary['generated']}. "
                f"Removed: {summary['removed']}. "
                f"Skipped: {summary['skipped']}."
            )
        )
