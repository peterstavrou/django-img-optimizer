import json
from io import BytesIO
from pathlib import Path

from django.conf import settings
from django.core.exceptions import ImproperlyConfigured
from PIL import Image, features


MANIFEST_FILENAME = '.django-img-optimizer.json'
OUTPUT_FORMATS = {
    'avif': {'pillow_format': 'AVIF', 'mime_type': 'image/avif'},
    'webp': {'pillow_format': 'WEBP', 'mime_type': 'image/webp'},
}


class ImageOptimizationError(Exception):
    """Raised when image optimization cannot safely continue."""


def get_settings():
    """Return validated image optimization settings."""
    image_root = getattr(settings, 'OPTIMIZE_IMAGE_ROOT', None)
    if not image_root:
        raise ImproperlyConfigured('Set OPTIMIZE_IMAGE_ROOT in settings.py')

    image_root = Path(image_root)
    if not image_root.is_dir():
        raise ImproperlyConfigured('OPTIMIZE_IMAGE_ROOT must be an existing directory')

    image_types = getattr(settings, 'OPTIMIZE_IMAGE_TYPES', ['jpg', 'jpeg', 'png'])
    if isinstance(image_types, str):
        image_types = [image_types]
    image_types = {image_type.lower().lstrip('.') for image_type in image_types}
    if image_types & OUTPUT_FORMATS.keys():
        raise ImproperlyConfigured('OPTIMIZE_IMAGE_TYPES cannot include AVIF or WebP')

    excluded_folders = getattr(settings, 'OPTIMIZE_IMAGE_EXCLUDED_FOLDERS', []) or []
    if isinstance(excluded_folders, str):
        excluded_folders = [excluded_folders]

    webp_quality = getattr(settings, 'OPTIMIZE_IMAGE_WEBP_QUALITY', 80)
    avif_quality = getattr(settings, 'OPTIMIZE_IMAGE_AVIF_QUALITY', 61)

    return {
        'OPTIMIZE_IMAGE_ROOT': image_root,
        'OPTIMIZE_IMAGE_TYPES': image_types,
        'OPTIMIZE_IMAGE_EXCLUDED_FOLDERS': set(excluded_folders),
        'OPTIMIZE_IMAGE_WEBP_QUALITY': _get_quality(
            'OPTIMIZE_IMAGE_WEBP_QUALITY', webp_quality
        ),
        'OPTIMIZE_IMAGE_AVIF_QUALITY': _get_quality(
            'OPTIMIZE_IMAGE_AVIF_QUALITY', avif_quality
        ),
    }


def delete_optimized_images():
    """Delete only AVIF and WebP files recorded as generated by this package."""
    image_root = get_settings()['OPTIMIZE_IMAGE_ROOT']
    managed_files = _load_generated_image_paths(image_root)
    deleted_count = 0

    for relative_path in managed_files:
        output_file = _resolve_generated_image_path(image_root, relative_path)
        if output_file.is_file():
            output_file.unlink()
            deleted_count += 1

    _save_generated_image_paths(image_root, set())
    return deleted_count


def optimize_images():
    """Generate AVIF and WebP alternatives for configured source images."""
    image_optimizer_settings = get_settings()
    image_root = image_optimizer_settings['OPTIMIZE_IMAGE_ROOT']
    _validate_format_support()
    source_files = _get_source_files(
        image_root,
        image_optimizer_settings['OPTIMIZE_IMAGE_TYPES'],
        image_optimizer_settings['OPTIMIZE_IMAGE_EXCLUDED_FOLDERS'],
    )
    _validate_output_collisions(source_files)

    managed_files = _load_generated_image_paths(image_root)
    new_managed_files = set()
    summary = {'generated': 0, 'removed': 0, 'skipped': 0}

    try:
        for source_file in source_files:
            _optimize_source_image(
                source_file,
                image_root,
                image_optimizer_settings,
                managed_files,
                new_managed_files,
                summary,
            )
    except ImageOptimizationError:
        _save_generated_image_paths(image_root, managed_files | new_managed_files)
        raise

    for relative_path in managed_files - new_managed_files:
        output_file = _resolve_generated_image_path(image_root, relative_path)
        if output_file.is_file():
            output_file.unlink()
            summary['removed'] += 1

    _save_generated_image_paths(image_root, new_managed_files)
    return summary


def _get_quality(setting_name, quality):
    """Validate a configured AVIF or WebP encoder quality value."""
    if isinstance(quality, bool) or not isinstance(quality, int) or not 0 <= quality <= 100:
        raise ImproperlyConfigured(
            f'{setting_name} must be an integer between 0 and 100'
        )
    return quality


def _validate_format_support():
    """Ensure Pillow can encode every format generated by this package."""
    for feature_name, display_name in [('avif', 'AVIF'), ('webp', 'WebP')]:
        try:
            is_supported = features.check(feature_name)
        except ValueError:
            is_supported = False

        if not is_supported:
            raise ImageOptimizationError(
                f'Pillow was installed without {display_name} support. '
                'Install a Pillow build with that encoder enabled.'
            )


def _get_source_files(image_root, image_types, excluded_folders):
    """Return source images beneath the configured root, excluding ignored folders."""
    return [
        file_path
        for file_path in sorted(image_root.rglob('*'))
        if file_path.is_file()
        and file_path.suffix.lower().lstrip('.') in image_types
        and not _is_excluded(file_path, image_root, excluded_folders)
    ]


def _is_excluded(file_path, image_root, excluded_folders):
    """Return whether a source image sits inside an excluded folder."""
    return any(
        folder_name in excluded_folders
        for folder_name in file_path.relative_to(image_root).parts[:-1]
    )


def _validate_output_collisions(source_files):
    """Reject source images that would generate the same output filenames."""
    output_sources = {}
    for source_file in source_files:
        output_sources.setdefault(source_file.with_suffix(''), []).append(source_file)

    collisions = [
        source_files
        for source_files in output_sources.values()
        if len(source_files) > 1
    ]
    if collisions:
        conflicting_files = ', '.join(file_path.name for file_path in collisions[0])
        raise ImageOptimizationError(
            'Multiple source images would create the same renditions: '
            f'{conflicting_files}. Rename one of them.'
        )


def _optimize_source_image(
    source_file,
    image_root,
    image_optimizer_settings,
    managed_files,
    new_managed_files,
    summary,
):
    """Generate smaller AVIF and WebP versions of one source image."""
    try:
        with Image.open(source_file) as source_image:
            image = _prepare_image(source_image)
            for output_format, output_settings in OUTPUT_FORMATS.items():
                output_file = source_file.with_suffix(f'.{output_format}')
                relative_output_path = output_file.relative_to(image_root).as_posix()

                if output_file.exists() and relative_output_path not in managed_files:
                    summary['skipped'] += 1
                    continue

                _save_rendition(
                    image,
                    output_file,
                    output_settings['pillow_format'],
                    image_optimizer_settings[
                        f'OPTIMIZE_IMAGE_{output_format.upper()}_QUALITY'
                    ],
                )

                if output_file.stat().st_size >= source_file.stat().st_size:
                    output_file.unlink()
                    if relative_output_path in managed_files:
                        summary['removed'] += 1
                    else:
                        summary['skipped'] += 1
                    continue

                new_managed_files.add(relative_output_path)
                summary['generated'] += 1
    except (OSError, ValueError, KeyError) as error:
        relative_source_path = source_file.relative_to(image_root)
        raise ImageOptimizationError(
            f'Could not optimize {relative_source_path}: {error}'
        ) from error


def _prepare_image(image):
    """Convert unsupported Pillow modes while preserving transparency when present."""
    if image.mode in {'RGB', 'RGBA'}:
        return image

    has_alpha = 'A' in image.getbands() or 'transparency' in image.info
    return image.convert('RGBA' if has_alpha else 'RGB')


def _save_rendition(image, output_file, pillow_format, quality):
    """Encode an image in memory, then write the completed optimized file."""
    with BytesIO() as image_data:
        image.save(image_data, pillow_format, quality=quality)
        output_file.write_bytes(image_data.getvalue())


def _load_generated_image_paths(image_root):
    """Return paths previously generated by this package from its manifest."""
    manifest_path = image_root / MANIFEST_FILENAME
    if not manifest_path.exists():
        return set()

    try:
        with manifest_path.open(encoding='utf-8') as manifest_file:
            manifest = json.load(manifest_file)
    except (OSError, json.JSONDecodeError) as error:
        raise ImageOptimizationError(f'Could not read {MANIFEST_FILENAME}: {error}') from error

    if not isinstance(manifest, dict) or not isinstance(manifest.get('files'), list):
        raise ImageOptimizationError(f'{MANIFEST_FILENAME} has an invalid format.')

    managed_files = set(manifest['files'])
    for relative_path in managed_files:
        _resolve_generated_image_path(image_root, relative_path)
    return managed_files


def _save_generated_image_paths(image_root, managed_files):
    """Record generated paths, or remove an empty manifest."""
    manifest_path = image_root / MANIFEST_FILENAME
    if not managed_files:
        manifest_path.unlink(missing_ok=True)
        return

    with manifest_path.open('w', encoding='utf-8') as manifest_file:
        json.dump({'files': sorted(managed_files)}, manifest_file, indent=2)
        manifest_file.write('\n')


def _resolve_generated_image_path(image_root, relative_path):
    """Resolve a manifest path and reject any path outside the image root."""
    image_root = image_root.resolve()
    output_file = (image_root / relative_path).resolve()
    try:
        output_file.relative_to(image_root)
    except ValueError as error:
        raise ImageOptimizationError(
            f'{MANIFEST_FILENAME} contains a file outside OPTIMIZE_IMAGE_ROOT.'
        ) from error
    return output_file
